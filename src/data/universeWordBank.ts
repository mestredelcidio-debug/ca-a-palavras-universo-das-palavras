/**
 * Obtém 6 palavras exclusivas e temáticas para um Modo Especial específico
 * Não repete palavras entre rodadas do mesmo modo e não usa palavras da campanha.
 */
export function getSpecialModeWords(modeId: number, levelNumber: number, count: number = 6): string[] {
  const pool = SPECIAL_MODE_WORD_POOLS[modeId] || SPECIAL_MODE_WORD_POOLS[1];
  const total = pool.length;
  const startIndex = ((levelNumber - 1) * count) % total;

  const result: string[] = [];
  const pickedSet = new Set<string>();

  for (let i = 0; i < total && result.length < count; i++) {
    const idx = (startIndex + i) % total;
    const w = pool[idx];
    if (!pickedSet.has(w)) {
      pickedSet.add(w);
      result.push(w);
    }
  }

  // Se faltar alguma palavra para fechar 6, completa com palavras do topo do pool
  for (let i = 0; i < total && result.length < count; i++) {
    const w = pool[i];
    if (!pickedSet.has(w)) {
      pickedSet.add(w);
      result.push(w);
    }
  }

  return result;
}

/**
 * Obtém 6 palavras exclusivas para uma fase específica da Campanha
 * Garante ZERO repetição entre fases consecutivas ou dentro do capítulo.
 */
export function getWordsForLevel(
  categoryId: string,
  levelNumber: number,
  count: number = 6,
  specialModeId?: number
): string[] {
  if (specialModeId && specialModeId >= 1 && specialModeId <= 15) {
    return getSpecialModeWords(specialModeId, levelNumber, count);
  }

  const pool = MASTER_CAMPAIGN_WORDS;
  const total = pool.length;
  // Deslocamento determinístico sem repetições
  const startIndex = ((levelNumber - 1) * count) % total;

  const result: string[] = [];
  const pickedSet = new Set<string>();

  for (let i = 0; i < total && result.length < count; i++) {
    const idx = (startIndex + i) % total;
    const w = pool[idx];
    if (!pickedSet.has(w)) {
      pickedSet.add(w);
      result.push(w);
    }
  }

  return result;
}
